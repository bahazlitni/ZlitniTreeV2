DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM "public"."_legacy_child_link_seed" AS seed
    LEFT JOIN "public"."persons" AS person ON person."id" = seed."child_id"
    WHERE person."id" IS NULL
  ) THEN
    RAISE EXCEPTION 'Cannot seed legacy child links: at least one child person is missing.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM "public"."_legacy_child_link_seed" AS seed
    LEFT JOIN "public"."marriages" AS marriage ON marriage."id" = seed."parent_marriage_id"
    WHERE marriage."id" IS NULL
  ) THEN
    RAISE EXCEPTION 'Cannot seed legacy child links: at least one parent marriage is missing.';
  END IF;
END $$;

UPDATE "public"."persons" AS person
SET "parent_marriage_id" = seed."parent_marriage_id"
FROM "public"."_legacy_child_link_seed" AS seed
WHERE person."id" = seed."child_id";

