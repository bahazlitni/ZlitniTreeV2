export type CountryOption = {
  value: string;
  label: string;
  name: string;
  searchText: string;
};

export function getCountryNameForCode(code: string, locale = "en") {
  const normalizedCode = code.trim().toUpperCase();

  if (normalizedCode.length !== 2) return code;

  const displayNames =
    typeof Intl.DisplayNames === "function"
      ? new Intl.DisplayNames([locale], { type: "region" })
      : null;

  return (
    displayNames?.of(normalizedCode) ?? FALLBACK_NAMES[normalizedCode] ?? code
  );
}

export function getCountryOptions() {
  return COUNTRY_CODES.map((code) => {
    const name = getCountryNameForCode(code, "en");

    return {
      value: code,
      label: `${code} - ${name}`,
      name,
      searchText: `${code} ${name}`.toLowerCase(),
    };
  }).sort((a, b) => a.name.localeCompare(b.name));
}
